const Age = 21;
if (Age > 0 && Age <= 5) {
    console.log("Toddler")
}else if (Age >= 6 && Age <= 12) {
     console.log("Child")
}else if (Age >= 13 && Age <= 17) {
     console.log("Teenager")
}else if (Age >= 18 && Age <= 59) {
      console.log("Adult")
}else if (Age >= 60) {
      console.log("Senior")
}